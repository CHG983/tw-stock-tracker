def _expand(groups: dict[str, str]) -> dict[str, str]:
    """把「產業 → 代號清單」展開成「代號 → 產業」；代號重複即為資料衝突，直接報錯。"""
    out: dict[str, str] = {}
    for industry, codes in groups.items():
        for code in str(codes).split(","):
            code = code.strip()
            if not code:
                continue
            if code in out and out[code] != industry:
                raise ValueError(f"代號 {code} 同時被歸為 {out[code]!r} 與 {industry!r}")
            out[code] = industry
    return out


